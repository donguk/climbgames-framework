using System;
using System.Linq;
using System.Text;

namespace ClimbGames.Editor.UI
{
    public partial class Binding
    {
        [Flags]
        public enum SchemaOption
        {
            None,

            Readonly = 1 << 0,
            Fallback = 1 << 1,
            AutoGeneratedType = 1 << 2,

            List = 1 << 3,
            Group = 1 << 4,
            UIBase = 1 << 5,
        }

        [Serializable]
        public class Schema
        {
            public SchemaOption options;
            public string prefix;
            [SelectTypes("Type")]
            public string typeName;
            [SelectTypes("")]
            public string[] fallback;

            public Schema(string prefix, Type type, Type[] fallback, SchemaOption options = SchemaOption.None)
            {
                this.prefix = prefix;
                typeName = type.AssemblyQualifiedName;
                this.fallback = fallback.Where(x => x != null).Select(x => x.AssemblyQualifiedName).ToArray();

                this.options = options;
                this.options |= SchemaOption.Fallback;
            }

            public Schema(string prefix, Type type, SchemaOption options)
            {
                this.prefix = prefix;
                typeName = type.AssemblyQualifiedName;

                this.options = options;
            }

            public Schema(string prefix, SchemaOption options)
            {
                this.prefix = prefix;
                typeName = "Auto Generated Type";

                this.options = options;
                this.options |= SchemaOption.AutoGeneratedType;
            }
        }
    }
}